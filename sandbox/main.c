/*
 * fatmap sandbox - SDL3 1280x720 framebuffer.
 *
 * Keys:
 *   1..9, 0, -, =  scene (gallery, blend modes, stress, texture, lines, aa vs aliased, 3d, troll,
 *            animated characters, helmet, shaders, seascape)
 *   S        cycle SIMD level (scalar / sse2 / avx2 / neon)
 *   A        toggle anti-aliasing (analytic / aliased)
 *   B        toggle bilinear filtering (image smoothing)
 *   T        toggle multithreaded command lists (deferred rendering)
 *   F        3d: cycle texture filter (nearest / bilinear / trilinear)
 *   M        3d: toggle perspective correct texturing (affine = PS1 look)
 *   N        3d: cycle MSAA (off / 4x / 8x)
 *   C        characters: cycle the fox animation clip
 *   G        shaders: cycle C shader programs / SPIR-V interpreted / SPIR-V compiled
 *            to C (build time) / fixed function T&L; seascape: interpreted / compiled
 *   Up/Down  seascape: render scale (1/1 .. 1/8, upscaled to the window)
 *   X        seascape: fast shader math (fm_fast_*, GPU precision) / 1 ulp math
 *
 * Frames are always rendered into the swapchain back buffer, then presented;
 * the presented front buffer is what gets uploaded to SDL.
 *   Up/Down  stress: double / halve object count
 *   P        print profiler report to the console
 *   V        toggle vsync
 *   Space    pause animation, Esc quit
 *
 * fatmap_sandbox --shots <dir>   renders every scene for 60 frames, prints the
 *                                average draw time, saves <dir>/scene_N.png, exits
 *                --scene N       (with --shots) only scene N (1 = gallery)
 */
